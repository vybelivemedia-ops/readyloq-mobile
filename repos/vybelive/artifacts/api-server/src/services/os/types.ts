// ─── Phase 3: Persistent State Engine ─────────────────────────────────────────

/**
 * Processing priority of an objective.
 * critical → high → medium → low.
 */
export type ObjectivePriority = "low" | "medium" | "high" | "critical";

/** Outcome of a single execution attempt on an objective. */
export type ExecutionOutcome = "success" | "failed" | "skipped" | "in_progress";

/**
 * A single entry in an objective's execution history.
 * Append-only — executives log actions here instead of relying on chat context.
 */
export interface ExecutionEntry {
  id: string;
  timestamp: Date;
  action: string;
  source: string;
  outcome: ExecutionOutcome;
  durationMs?: number;
  detail?: string;
}

/**
 * A single insight logged during an objective's lifecycle.
 * Replaces conversational memory as the durable learning record.
 */
export interface LearningEntry {
  id: string;
  timestamp: Date;
  topic: string;
  insight: string;
  /** Confidence 0–100. */
  confidence: number;
  source: string;
}

/**
 * Descriptor of what an executive recommends should happen next on an objective.
 * Persisted to DB — survives server restarts and session boundaries.
 */
export interface NextActionDescriptor {
  kind: string;
  description: string;
  assignedTo?: string;
  requiredBy?: string;
  estimatedEffort?: string;
}

/**
 * Full persistent state of a single objective — the Phase 3 enrichment of OSObjective.
 *
 * Objectives exist independently of chat. Executives query RichObjectiveState
 * from the ObjectiveStateStore instead of reconstructing context from messages.
 */
export interface RichObjectiveState extends OSObjective {
  /** Executive role slug that owns this objective (e.g. "cto"). Null if unassigned. */
  ownerRole: string | null;
  priority: ObjectivePriority;
  /** IDs of objectives this one blocks on. */
  dependencies: string[];
  /** Completion progress 0–100. */
  progressPercent: number;
  /** Number of times execution has been retried after failure. */
  retryCount: number;
  executionHistory: ExecutionEntry[];
  learningHistory: LearningEntry[];
  /** What an executive has said should happen next. Null if not set. */
  nextAction: NextActionDescriptor | null;
}

/**
 * Full operational context for an executive, assembled by the ExecutiveStateReader.
 * This is the Phase 3 replacement for chat-history / conversational-memory lookups.
 */
export interface ExecutiveContext {
  role: string;
  /** All objectives owned by this executive role, with full rich state. */
  ownedObjectives: RichObjectiveState[];
  /** Snapshot of global OS state metrics. */
  systemState: {
    activeObjectiveCount: number;
    pendingApprovalCount: number;
    lastAutonomyCycleAt: string | null;
    agentZeroHealthy: boolean;
  };
  /** All in-progress objectives across the whole system (for cross-role awareness). */
  activeSystemObjectives: RichObjectiveState[];
  queriedAt: Date;
}

// ─── Phase 4: Chief of Staff ──────────────────────────────────────────────────

export type CoSDecisionKind =
  | "assign"
  | "priority_change"
  | "escalate"
  | "flag_blocked"
  | "balance"
  | "no_change";

/** A single coordination decision made by Quinn in her CoS role. */
export type CoSDecision = {
  kind: CoSDecisionKind;
  objectiveId: string;
  objectiveTitle: string;
  /** Previous value (role, priority level, etc.) before the decision. */
  from?: string;
  /** New value (role, priority level, etc.) after the decision. */
  to?: string;
  reason: string;
  appliedAt: string;
};

/** Per-executive objective workload snapshot. */
export type WorkloadItem = {
  role: string;
  name: string | null;
  execId: string;
  objectiveCount: number;
  byPriority: Record<string, number>;
  overloaded: boolean;
};

export type BlockedReason = "unmet_dependency" | "stalled_progress" | "no_owner";

/** An objective that Quinn has flagged as blocked or stalled. */
export type BlockedObjective = {
  id: string;
  title: string;
  status: string;
  blockedReason: BlockedReason;
  /** IDs of unresolved dependencies (when blockedReason === "unmet_dependency"). */
  dependencyIds?: string[];
  /** ISO timestamp of the last recorded activity entry. */
  lastActivityAt?: string | null;
  /** Milliseconds since the last activity (for stalled objectives). */
  stalledForMs?: number;
};

/** Full result of a Quinn Chief of Staff coordination cycle. */
export type CoSCycleResult = {
  cycleId: string;
  startedAt: string;
  completedAt: string;
  decisions: CoSDecision[];
  workload: WorkloadItem[];
  blocked: BlockedObjective[];
  summary: string;
};

/** Persistent runtime status of the QuinnChiefOfStaff singleton. */
export type ChiefOfStaffStatus = {
  lastCycleAt: string | null;
  lastCycleDecisionCount: number;
  totalCyclesRun: number;
  blockedCount: number;
  overloadedExecCount: number;
};

